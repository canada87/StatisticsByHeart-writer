class RecordIn(_Strict):
    type: TypeName
    hc_id: HcId
    start_time: AwareDatetime
    end_time: AwareDatetime | None = None
    start_offset_s: OffsetS | None = None
    end_offset_s: OffsetS | None = None
    source: SourceIn
    last_modified: AwareDatetime
    data: dict[str, Any] = Field(default_factory=dict)

    _spec: TypeSpec = PrivateAttr()
    _parsed: BaseModel = PrivateAttr()

    @model_validator(mode="after")
    def _validate_semantics(self) -> RecordIn:
        spec = SPECS.get(self.type)
        if spec is None:
            raise ValueError(f"unsupported_type: {self.type}")
        self.start_time = _to_utc(self.start_time, "start_time")
        self.last_modified = _to_utc(self.last_modified, "last_modified")
        if self.end_time is not None:
            self.end_time = _to_utc(self.end_time, "end_time")
            if self.end_time < self.start_time:
                raise ValueError("end_time must not precede start_time")
        elif spec.end_required:
            raise ValueError(f"end_time is required for {spec.shape.value} type {spec.name}")
        if spec.shape is Shape.INSTANT and self.end_time == self.start_time:
            self.end_time = None
        self._spec = spec
        self._parsed = spec.model.model_validate(self.data)
        return self

    @property
    def spec(self) -> TypeSpec:
        return self._spec

    @property
    def parsed(self) -> BaseModel:
        return self._parsed


