OffsetS = Annotated[int, Field(ge=-64_800, le=64_800)]  # +-18h, Health Connect ZoneOffset range
Str100 = Annotated[str, Field(max_length=100)]
HcId = Annotated[str, Field(min_length=1, max_length=128)]
TypeName = Annotated[str, Field(min_length=1, max_length=64)]
SANE_YEARS = range(2000, 2101)


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


def _to_utc(dt: datetime, field: str) -> datetime:
    if dt.year not in SANE_YEARS:
        raise ValueError(f"{field} out of range (year must be 2000..2100)")
    return dt.astimezone(UTC)


