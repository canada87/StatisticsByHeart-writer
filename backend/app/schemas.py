class DailyAggregateItem(_Strict):
    date: Date = Field(description="Local calendar day, as defined by the Reader's HC period")
    type: TypeName
    sum: float | None = None
    avg: float | None = None
    min: float | None = None
    max: float | None = None
    count: int | None = Field(default=None, ge=0)
    data_origins: Annotated[list[str], Field(max_length=20)] | None = Field(
        default=None, description="Packages HC reports as contributing to the aggregate"
    )
    snapshot_at: AwareDatetime | None = Field(
        default=None, description="When the Reader computed it; older snapshots never overwrite"
    )

    @model_validator(mode="after")
    def _check(self) -> DailyAggregateItem:
        if self.type not in SPECS:
            raise ValueError(f"unsupported_type: {self.type}")
        stats = (self.sum, self.avg, self.min, self.max)
        if all(v is None for v in (*stats, self.count)):
            raise ValueError("at least one of sum/avg/min/max/count is required")
        if any(v is not None and not math.isfinite(v) for v in stats):
            raise ValueError("sum/avg/min/max must be finite")
        if self.snapshot_at is not None:
            self.snapshot_at = self.snapshot_at.astimezone(UTC)
        return self


LenientAggregate = Annotated[DailyAggregateItem | dict[str, Any], Field(union_mode="left_to_right")]


